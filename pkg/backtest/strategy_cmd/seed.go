package strategy_cmd

import (
	"flag"
	"fmt"
	"io"
	"log"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/darianmavgo/trade_well/pkg/backtest/appenv"
	"github.com/darianmavgo/trade_well/pkg/backtest/refdb"
)

var identifier = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)

// seedMain is `strategy seed`.
func seedMain() {
	table := flag.String("table", "", "table to dump, like hmm_strategy")
	ids := flag.String("ids", "", "only these row ids, comma-separated (default: every row)")
	out := flag.String("out", "", "seed file to write (default sql/seed/<table>.sql)")
	ref := flag.String("ref", appenv.RefDB(), "reference database to read")
	force := flag.Bool("force", false, "overwrite the seed file if it exists")
	dryRun := flag.Bool("dry-run", false, "print the seed to the terminal and write nothing")
	flag.Parse()
	var list []string
	for _, id := range strings.Split(*ids, ",") {
		if id = strings.TrimSpace(id); id != "" {
			list = append(list, id)
		}
	}
	path := *out
	if path == "" && *table != "" {
		path = filepath.Join("sql", "seed", *table+".sql")
	}
	if err := SeedFile(os.Stdout, *ref, *table, list, path, *force, *dryRun); err != nil {
		log.Fatal(err)
	}
}

// SeedFile writes the seed of table (see Seed) to path. It refuses to replace an existing file
// unless force is set, since a hand-written seed carries comments the dump cannot. With dryRun
// the seed goes to out and nothing is written.
func SeedFile(out io.Writer, refPath, table string, ids []string, path string, force, dryRun bool) error {
	if dryRun {
		return Seed(out, refPath, table, ids)
	}
	if path == "" {
		return fmt.Errorf("seed needs -table <name>")
	}
	if _, err := os.Stat(path); err == nil && !force {
		return fmt.Errorf("%s exists: use -force to replace it (a hand-written seed's comments are not kept)", path)
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	f, err := os.CreateTemp(filepath.Dir(path), ".seed-*")
	if err != nil {
		return err
	}
	defer os.Remove(f.Name())
	if err := Seed(f, refPath, table, ids); err != nil {
		f.Close()
		return err
	}
	if err := f.Close(); err != nil {
		return err
	}
	if err := os.Rename(f.Name(), path); err != nil {
		return err
	}
	fmt.Fprintf(out, "wrote %s (%s from %s). Run it with: sqlite3 <database> < %s\n", path, table, refPath, path)
	return nil
}

// Seed writes the SQL that recreates table: its CREATE TABLE IF NOT EXISTS and one
// INSERT OR REPLACE per row (all rows, or only ids), ordered by id. The values are rendered by
// SQLite's quote(), so the script reloads to the same rows. The table must have an id column.
func Seed(out io.Writer, refPath, table string, ids []string) error {
	if !identifier.MatchString(table) {
		return fmt.Errorf("seed needs -table <name>, got %q", table)
	}
	db, err := refdb.Open(refPath)
	if err != nil {
		return err
	}
	defer db.Close()

	var create string
	if err := db.Get(&create, `SELECT sql FROM sqlite_master WHERE type = 'table' AND name = ?`, table); err != nil {
		return fmt.Errorf("no table %q in %s", table, refPath)
	}
	var cols []string
	if err := db.Select(&cols, `SELECT name FROM pragma_table_info(?) ORDER BY cid`, table); err != nil {
		return err
	}
	hasID := false
	for _, c := range cols {
		if c == "id" {
			hasID = true
		}
	}
	if !hasID {
		return fmt.Errorf("table %s has no id column, so its rows cannot be ordered or picked", table)
	}

	// SQL builds each INSERT: quote() renders every value as a SQL literal.
	quoted := make([]string, len(cols))
	for i, c := range cols {
		quoted[i] = "quote(" + `"` + c + `"` + ")"
	}
	query := `SELECT 'INSERT OR REPLACE INTO ` + table + ` (` + strings.Join(cols, ", ") + `) VALUES (' || ` +
		strings.Join(quoted, ` || ', ' || `) + ` || ');' FROM ` + table
	var args []any
	if len(ids) > 0 {
		query += ` WHERE id IN (?` + strings.Repeat(", ?", len(ids)-1) + `)`
		for _, id := range ids {
			args = append(args, id)
		}
	}
	query += ` ORDER BY id`
	var inserts []string
	if err := db.Select(&inserts, query, args...); err != nil {
		return err
	}
	if len(ids) > 0 && len(inserts) != len(ids) {
		return fmt.Errorf("asked for %d ids in %s, found %d rows", len(ids), table, len(inserts))
	}

	create = strings.Replace(create, "CREATE TABLE ", "CREATE TABLE IF NOT EXISTS ", 1)
	fmt.Fprintf(out, "-- Generated by `strategy seed -table %s`. Edit the rows with a strategy command or SQL, then dump again.\n", table)
	fmt.Fprintf(out, "-- Run: sqlite3 refdata/strategies.db < sql/seed/%s.sql\n", table)
	fmt.Fprintf(out, "%s;\n\n", create)
	for _, in := range inserts {
		fmt.Fprintln(out, in)
	}
	return nil
}

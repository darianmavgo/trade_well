-- Slice tables for one BDC Schedule of Investments analytical pass in the scratch calc database.
-- Each stage after this file reads the slice table written by the previous stage.
DROP TABLE IF EXISTS bdc_slice_normalized;
CREATE TABLE bdc_slice_normalized (
    accession_number  TEXT NOT NULL,
    bdc_ticker        TEXT NOT NULL,
    manager           TEXT NOT NULL,
    form              TEXT NOT NULL,
    filing_date       TEXT NOT NULL,
    report_date       TEXT NOT NULL,
    row_num           INTEGER NOT NULL,
    borrower_name     TEXT NOT NULL,
    borrower_upper    TEXT NOT NULL,
    industry          TEXT NOT NULL,
    industry_upper    TEXT NOT NULL,
    investment_type   TEXT NOT NULL,
    inv_type_upper    TEXT NOT NULL,
    reference_rate    TEXT NOT NULL,
    spread_bps        REAL NOT NULL,
    interest_rate_pct REAL NOT NULL,
    pik_rate_pct      REAL NOT NULL,
    floor_rate_pct    REAL NOT NULL,
    rate_text         TEXT NOT NULL,
    acquisition_date  TEXT NOT NULL,
    maturity_date     TEXT NOT NULL,
    principal_amount  REAL NOT NULL,
    amortized_cost    REAL NOT NULL,
    fair_value        REAL NOT NULL,
    non_accrual       INTEGER NOT NULL,
    footnotes         TEXT NOT NULL
);

